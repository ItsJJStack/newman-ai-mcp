/**
 * @fileoverview Postman collection parser and static analyzer (parser.ts).
 * Recursively traverses folders and items, extracts URLs (string or object),
 * statically validates scripts with vm.Script, and detects forbidden APIs and variables.
 */
import vm from 'node:vm';

/** Normalized structure of an inspectable request */
export type ParsedItem = {
  path: string[];
  name: string;
  method: string;
  url: string;
  hasTest: boolean;
  hasPrerequest: boolean;
  rawItem: any;
};

/** Issue detected during static validation. */
export type ValidationIssue = {
  severity: 'error' | 'warning';
  rule: 'json' | 'schema' | 'syntax' | 'forbidden_api' | 'template_in_js' | 'undefined_variable' | 'runtime_variable';
  location: string;
  message: string;
};

/**
 * Converts a Postman URL (string or object) to a readable string.
 * @param urlAttr Postman URL attribute (string or { raw, host, path, ... })
 * @returns URL as string
 */
export function normalizeUrl(urlAttr: any): string {
  if (!urlAttr) return '';
  if (typeof urlAttr === 'string') return urlAttr;
  if (typeof urlAttr === 'object') {
    if (typeof urlAttr.raw === 'string' && urlAttr.raw) {
      return urlAttr.raw;
    }
    // If it's a structured object (e.g., generated by openapi-to-postmanv2)
    const host = Array.isArray(urlAttr.host) ? urlAttr.host.join('.') : (urlAttr.host || '');
    const pathParts = Array.isArray(urlAttr.path)
      ? urlAttr.path.map((p: any) => (typeof p === 'object' && p !== null ? `{{${p.key}}}` : p)).join('/')
      : (urlAttr.path || '');
    
    const base = host ? (host.startsWith('http') ? host : `https://${host}`) : '';
    const full = base ? `${base}/${pathParts.replace(/^\/+/, '')}` : pathParts;
    return full || '';
  }
  return String(urlAttr);
}

/**
 * Recursively traverses a collection and extracts all request items.
 * @param items Array of items (folder or request)
 * @param currentPath Current folder path
 * @returns List of normalized items
 */
export function extractItems(items: any[], currentPath: string[] = []): ParsedItem[] {
  const result: ParsedItem[] = [];
  if (!Array.isArray(items)) return result;

  for (const item of items) {
    if (!item) continue;
    if (Array.isArray(item.item)) {
      // This is a folder.
      const folderName = item.name || 'Folder';
      result.push(...extractItems(item.item, [...currentPath, folderName]));
    } else if (item.request) {
      // This is a request.
      const itemName = item.name || 'Request';
      const req = item.request;
      const method = req.method || 'GET';
      const url = normalizeUrl(req.url);

      let hasTest = false;
      let hasPrerequest = false;

      if (Array.isArray(item.event)) {
        for (const ev of item.event) {
          if (ev.listen === 'test' && ev.script?.exec) hasTest = true;
          if (ev.listen === 'prerequest' && ev.script?.exec) hasPrerequest = true;
        }
      }

      result.push({
        path: currentPath,
        name: itemName,
        method,
        url,
        hasTest,
        hasPrerequest,
        rawItem: item,
      });
    }
  }

  return result;
}

/**
 * Extracts all `{{variable}}` references from text,
 * ignoring dynamic variables such as `{{$...}}`.
 * @param text Text to analyze
 * @returns Set of referenced variable names
 */
export function extractVariableReferences(text: string): Set<string> {
  const refs = new Set<string>();
  if (typeof text !== 'string') return refs;

  const regex = /\{\{([^\}]+)\}\}/g;
  let match;
  while ((match = regex.exec(text)) !== null) {
    const varName = match[1]?.trim();
    if (varName && !varName.startsWith('$')) {
      refs.add(varName);
    }
  }
  return refs;
}

/**
 * Statically validates a Postman collection (Tool 7).
 * @param collection Deserialized collection object
 * @param envData Optional environment object
 * @param globalsData Optional globals object
 * @param iterationData Optional array of iteration-data rows
 * @returns Validity, issue list, and summary
 */
export function validateCollectionStatic(
  collection: any,
  envData?: any,
  globalsData?: any,
  iterationData?: any[]
): { valid: boolean; issues: ValidationIssue[]; summary: { errors: number; warnings: number } } {
  const issues: ValidationIssue[] = [];

  // 1. Validate the basic structure.
  if (!collection || typeof collection !== 'object') {
    issues.push({
      severity: 'error',
      rule: 'schema',
      location: 'root',
      message: 'Collection is not a valid JSON object.',
    });
    return { valid: false, issues, summary: { errors: 1, warnings: 0 } };
  }

  if (!collection.info || !Array.isArray(collection.item)) {
    issues.push({
      severity: 'error',
      rule: 'schema',
      location: 'root',
      message: 'Invalid Postman v2.1 structure: missing info or item[].',
    });
  }

  // Recopilar variables definidas
  const definedVars = new Set<string>();
  if (Array.isArray(collection.variable)) {
    for (const v of collection.variable) {
      if (v && typeof v.key === 'string') definedVars.add(v.key);
    }
  }

  if (envData && typeof envData === 'object') {
    const envValues = Array.isArray(envData.values) ? envData.values : Object.entries(envData);
    for (const v of envValues) {
      if (Array.isArray(envData.values) && v && typeof v.key === 'string') {
        if (v.enabled !== false) definedVars.add(v.key);
      } else if (!Array.isArray(envData.values) && typeof v === 'object' && v !== null) {
        // Objeto plano
      } else if (Array.isArray(envValues)) {
        // Par key-value
        if (typeof (v as any).key === 'string') definedVars.add((v as any).key);
      }
    }
    // If envData is a plain key-value object
    if (!envData.values && !Array.isArray(envData)) {
      for (const k of Object.keys(envData)) {
        definedVars.add(k);
      }
    }
  }

  if (globalsData && typeof globalsData === 'object') {
    const globValues = Array.isArray(globalsData.values) ? globalsData.values : Object.entries(globalsData);
    for (const v of globValues) {
      if (Array.isArray(globalsData.values) && v && typeof v.key === 'string') {
        if (v.enabled !== false) definedVars.add(v.key);
      } else if (!Array.isArray(globalsData.values)) {
        if (typeof v[0] === 'string') definedVars.add(v[0]);
      }
    }
    if (!globalsData.values && !Array.isArray(globalsData)) {
      for (const k of Object.keys(globalsData)) {
        definedVars.add(k);
      }
    }
  }

  const iterationColumns = new Set<string>();
  if (Array.isArray(iterationData) && iterationData.length > 0 && iterationData[0]) {
    for (const k of Object.keys(iterationData[0])) {
      iterationColumns.add(k);
      definedVars.add(k);
    }
  }

  // Variables created in scripts (pm.*.set).
  const scriptDefinedVars = new Set<string>();
  const runtimeRefs = new Set<string>();
  function collectSetVariables(nodes: any[]) {
    for (const node of nodes ?? []) {
      if (Array.isArray(node.item)) collectSetVariables(node.item);
      for (const ev of node.event ?? []) {
        const code = (Array.isArray(ev.script?.exec) ? ev.script.exec : [ev.script?.exec]).filter(Boolean).join('\n');
        const setRegex = /pm\.(?:environment|globals|collectionVariables|variables)\.set\s*\(\s*['"]([^'"]+)['"]/g;
        for (const match of code.matchAll(setRegex)) if (match[1]) scriptDefinedVars.add(match[1]);
      }
    }
  }
  collectSetVariables(collection.item ?? []);

  function maskScript(source: string): string {
    return source
      .replace(/\/\*[\s\S]*?\*\//g, match => match.replace(/[^\r\n]/g, ' '))
      .replace(/(^|\s)\/\/.*$/gm, match => match.replace(/[^\r\n]/g, ' '))
      .replace(/(['"`])(?:\\.|(?!\1)[\s\S])*?\1/g, match => match.replace(/[^\r\n]/g, ' '));
  }

  // Analyze scripts and requests recursively
  function inspectNode(nodes: any[], currentPath: string[] = []) {
    if (!Array.isArray(nodes)) return;

    for (const node of nodes) {
      if (!node) continue;
      const nodeName = node.name || 'Item';
      const nodePathStr = [...currentPath, nodeName].join('/');

      if (Array.isArray(node.item)) {
        inspectNode(node.item, [...currentPath, nodeName]);
      }

      // Eventos (scripts)
      if (Array.isArray(node.event)) {
        for (const ev of node.event) {
          const listen = ev.listen || 'script';
          const scriptExec = ev.script?.exec;
          if (!scriptExec) continue;

          const lines = Array.isArray(scriptExec) ? scriptExec : [String(scriptExec)];
          const fullCode = lines.join('\n');
          const maskedCode = maskScript(fullCode);

          // 1. Validar sintaxis con vm.Script
          let syntaxError: any;
          try {
            new vm.Script(fullCode, { filename: `${nodePathStr} > ${listen}` });
          } catch (err: any) {
            syntaxError = err;
            issues.push({
              severity: 'error',
              rule: 'syntax',
              location: `${nodePathStr} > ${listen} > line ${Number.isInteger(err.lineNumber) ? err.lineNumber : 1}`,
              message: err.message || 'Script syntax error',
            });
          }

          // 2. Detect forbidden or unavailable APIs
          // - await outside async
          if (/\bawait\b/.test(maskedCode) && syntaxError && /await is only valid|Unexpected reserved word/i.test(syntaxError.message ?? '')) {
            issues[issues.length - 1]!.location = `${nodePathStr} > ${listen} > line ${Number.isInteger(syntaxError.lineNumber) ? syntaxError.lineNumber : 1}`;
            issues[issues.length - 1]!.message = 'Top-level await is not supported in Newman 6.2.3.';
          }

          // - pm.environmentVariables / pm.globalVariables
          if (/pm\.(environmentVariables|globalVariables)/.test(maskedCode)) {
            issues.push({
              severity: 'error',
              rule: 'forbidden_api',
              location: `${nodePathStr} > ${listen} > line ${lineForMatch(maskedCode, /pm\.(environmentVariables|globalVariables)/)}`,
              message: "API unavailable in Newman: pm.environmentVariables or pm.globalVariables.",
            });
          }

          // - require('crypto') u otros prohibidos
          if (/require\s*\(\s*['"](crypto|fs|child_process|http|https|net)['"]\s*\)/.test(maskedCode)) {
            issues.push({
              severity: 'error',
              rule: 'forbidden_api',
              location: `${nodePathStr} > ${listen} > line ${lineForMatch(maskedCode, /require\s*\(/)}`,
              message: "Module is forbidden or unavailable in Newman (for example, require('crypto')).",
            });
          }

          // - window, document, fetch, XMLHttpRequest, localStorage, process.
          if (/\b(window|document|fetch|XMLHttpRequest|localStorage|sessionStorage|navigator|alert)\b/.test(maskedCode)) {
            issues.push({
              severity: 'error',
              rule: 'forbidden_api',
              location: `${nodePathStr} > ${listen} > line ${lineForMatch(maskedCode, /\b(window|document|fetch|XMLHttpRequest|localStorage|sessionStorage|navigator|alert)\b/)}`,
              message: 'Browser or global API is forbidden in Newman (e.g. window, document, fetch).',
            });
          }

          // - {{...}} used as JavaScript code
          const templateInCodeRegex = /(?:const|let|var|\=|\+|\-|\*|\/|\(|\,|\:)\s*\{\{([^\}]+)\}\}/g;
          if (templateInCodeRegex.test(maskedCode) || /\{\{[^\}]+\}\}\s*[\+\-\*\/\=]/.test(maskedCode)) {
            issues.push({
              severity: 'error',
              rule: 'template_in_js',
              location: `${nodePathStr} > ${listen} > line ${lineForMatch(maskedCode, templateInCodeRegex)}`,
              message: 'Using {{variable}} as JavaScript code in a script (use pm.variables.get).',
            });
          }

          // - Detect pm.*.set to register variables created at runtime
          const setVarRegex = /pm\.(?:environment|globals|collectionVariables|variables)\.set\s*\(\s*['"]([^'"]+)['"]/g;

          // Extract variable references inside the script (e.g., pm.variables.get("foo") or replaceIn)
          const refMatches = maskedCode.matchAll(/replaceIn\s*\(\s*['"][^'"]*\{\{([^\}]+)\\}\}[^'"]*['"]\s*\)/g);
          for (const rm of refMatches) {
            if (rm[1] && !rm[1].startsWith('$')) {
              // Referenced in script
            }
          }
        }
      }

      // Validate variable references in URL, headers, body, and request auth
      if (node.request) {
        const req = node.request;
        const serializedReq = JSON.stringify({
          url: req.url,
          header: req.header,
          body: req.body,
          auth: req.auth,
        });

        const varRefs = extractVariableReferences(serializedReq);
        for (const refVar of varRefs) {
          if (!definedVars.has(refVar) && scriptDefinedVars.has(refVar)) {
            runtimeRefs.add(refVar);
          } else if (!definedVars.has(refVar) && !refVar.startsWith('$')) {
            // Check if it's an error or warning (if created in script it's a warning, if it doesn't exist it's an error)
            issues.push({
              severity: 'error',
              rule: 'undefined_variable',
              location: nodePathStr,
              message: `Undefined variable: {{${refVar}}}`,
            });
          }
        }
      }
    }
  }

  if (collection.item) {
    inspectNode(collection.item);
  }
  for (const variable of runtimeRefs) {
    issues.push({ severity: 'warning', rule: 'runtime_variable', location: 'collection', message: `Runtime variable: {{${variable}}}` });
  }

  // Count errors and warnings
  let errors = 0;
  let warnings = 0;
  for (const issue of issues) {
    if (issue.severity === 'error') errors++;
    else warnings++;
  }

  return {
    valid: errors === 0,
    issues,
    summary: { errors, warnings },
  };
}

function lineForMatch(source: string, pattern: RegExp): number {
  const match = pattern.exec(source);
  return match ? source.slice(0, match.index).split('\n').length : 1;
}
